export function buildChineseReviewPrompt(script) {
  const reviewData = {
    topic: script.topic,
    title: script.title,
    hook: script.hook,
    presentationStyle: script.presentationStyle,
    scenes: (script.scenes || []).map((scene) => scene.description),
    lessons: (script.dialogues || []).map(({ chinese, pinyin, vietnamese, term, termPinyin, meaningVi, noteVi, grammarNote }) => ({
      chinese, pinyin, vietnamese, term, termPinyin, meaningVi, noteVi, grammarNote
    })),
    caption: script.caption,
    speechSegments: (script.speechSegments || []).map(({ segmentId, language, state, text }) => ({ segmentId, language, state, text }))
  };
  return `Review this Vietnamese–Simplified Chinese beginner-video script as a strict Mandarin editor and Vietnamese–Chinese translator. Treat this as a fresh review; do not assume the draft is correct because it was generated by an AI. Check every lesson and caption carefully.\n` +
    `Fail the draft if any Chinese sentence is unnatural, ungrammatical, not Simplified Chinese, has punctuation that conflicts with its intent, or does not fit the stated presentation style. Independently check that every Vietnamese line faithfully matches the Chinese sentence and does not omit or add meaning. Check the full-sentence Pinyin and key-phrase Pinyin syllable by syllable, including tone placement, the actual reading of each Hanzi, and whether the key phrase occurs in the sentence. Use standard Hanyu Pinyin word grouping; neutral tones may be unmarked and 儿化 may attach 儿 to the preceding syllable. Check that meanings, usage notes, grammar notes, scene continuity, caption explanations, and captions' Pinyin claims are supported by the lesson data. Check that the spoken sequence reads naturally and ends with lesson content, with no follow/subscribe CTA or extra ending speech. If uncertain about an item, fail it and identify the exact lesson and field.\n` +
    `Return only JSON in this exact shape: {"approved":true,"issues":[]} when every check passes, or {"approved":false,"issues":["lesson 1 pinyin: ..."]} when any check fails. Do not rewrite the script, do not provide general praise, and do not use issues as optional suggestions.\n` +
    `Draft: ${JSON.stringify(reviewData)}`;
}

export function assertChineseReviewResponse(value) {
  let response = value;
  if (typeof value === 'string') {
    const clean = value.trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '');
    const start = clean.indexOf('{');
    const end = clean.lastIndexOf('}');
    if (start < 0 || end < start) throw new Error('Lượt rà soát tiếng Trung không trả về JSON hợp lệ.');
    try { response = JSON.parse(clean.slice(start, end + 1)); }
    catch { throw new Error('Lượt rà soát tiếng Trung không trả về JSON hợp lệ.'); }
  }
  if (!response || typeof response !== 'object' || Array.isArray(response)
    || typeof response.approved !== 'boolean' || !Array.isArray(response.issues)
    || response.issues.some((issue) => typeof issue !== 'string')
    || Object.keys(response).some((key) => !['approved', 'issues'].includes(key))) {
    throw new Error('Lượt rà soát tiếng Trung trả sai cấu trúc; job bị chặn để tránh render nội dung chưa kiểm định.');
  }
  const issues = response.issues.map((issue) => issue.trim()).filter(Boolean);
  if (!response.approved || issues.length) {
    throw new Error(`Rà soát tiếng Trung chưa đạt: ${issues.join(' | ') || 'người rà soát không xác nhận nội dung đạt chuẩn.'}`);
  }
  return { approved: true, issues: [] };
}
