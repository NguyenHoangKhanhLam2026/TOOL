export function createMotPhutVoLeManualSchedule(contentId, localDateTime) {
  const settings = getMotPhutVoLeSettings();
  const scheduledAt = zonedLocalToDate(localDateTime, TIMEZONE);
  if (!Number.isFinite(scheduledAt.getTime()) || scheduledAt <= new Date()) throw new Error('Thời điểm đăng MPVL phải ở tương lai.');
  if (settings.autoPublishEnabled && scheduledAt.getTime() < Date.now() + 10 * 60_000) {
    throw new Error('Facebook cần nhận lịch MPVL trước ít nhất 10 phút.');
  }
  const target = localScheduleSlot(scheduledAt, TIMEZONE);
  const occupied = listMotPhutVoLeSchedules().filter((item) => item.countsTowardLimit);
  const dayItems = occupied.map((item) => ({ ...localScheduleSlot(item.scheduledAt, TIMEZONE), item })).filter((item) => item.day === target.day);
  if (dayItems.some((item) => item.minute === target.minute)) throw Object.assign(new Error('Ngày này đã có MPVL ở khung giờ đó.'), { statusCode: 409 });
  if (dayItems.length >= settings.postsPerDay) throw Object.assign(new Error('Ngày này đã đủ số video MPVL theo giới hạn mỗi ngày.'), { statusCode: 409 });
  return createMotPhutVoLeSchedule(contentId, scheduledAt);
}

export function deleteMotPhutVoLeScheduleFromApp(id) {
  return deleteMotPhutVoLeSchedule(id);
}

export async function processMotPhutVoLeScheduleTick({ onError = () => {} } = {}) {
  const settings = getMotPhutVoLeSettings();
  recoverMotPhutVoLeSchedules();
  const schedules = listMotPhutVoLeSchedules().filter((item) => item.countsTowardLimit);
  const videos = listMotPhutVoLeVideos({ limit: 1000 });
  const alreadyScheduled = new Set(schedules.map((item) => item.contentId));
  const ready = videos.filter((item) => item.status === 'complete' && item.videoPath && !alreadyScheduled.has(item.id));
  const preparedUntil = Date.now() + settings.prepareAheadDays * 24 * 60 * 60_000;
  const preparedCount = schedules.filter((item) => Date.parse(item.scheduledAt) <= preparedUntil && Date.parse(item.scheduledAt) > Date.now()).length;
  const targetCount = settings.autoScheduleEnabled ? settings.postsPerDay * settings.prepareAheadDays : settings.postsPerDay;

  if (settings.autoScheduleEnabled && ready.length && preparedCount < targetCount) {
    try {
      const next = randomNextScheduledTime(new Date(), TIMEZONE, settings.postsPerDay, schedules);
      const scheduled = createMotPhutVoLeSchedule(ready[0].id, next);
      logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_AUTO_SCHEDULE_CREATED',
        'Đã tự xếp video MPVL ' + ready[0].id.slice(0, 8) + ' vào lịch ' + scheduled.scheduledAt + '.');
    } catch (error) {
      logMotPhutVoLeActivity('WARN', 'MOT_PHUT_VO_LE_AUTO_SCHEDULE_FAILED', 'Không thể tự xếp lịch MPVL: ' + error.message);
      onError(error);
    }
  }

  const availableContentCount = settings.autoScheduleEnabled ? preparedCount + ready.length : ready.length;
  if (settings.autoGenerationEnabled && availableContentCount < targetCount) {
    const today = localScheduleSlot(new Date(), TIMEZONE).day;
    const jobs = listMotPhutVoLeJobs({ limit: 500 });
    const activeCreate = jobs.some((job) => job.type === 'create' && ['pending', 'running'].includes(job.status));
    const createdToday = jobs.filter((job) => job.type === 'create' && localScheduleSlot(job.createdAt, TIMEZONE).day === today).length;
    const lastAutoCreate = jobs.find((job) => job.type === 'create' && job.payload.autoGenerated === true);
    const retryCoolingDown = lastAutoCreate?.status === 'failed' && Date.now() - Date.parse(lastAutoCreate.updatedAt) < 30 * 60_000;
    if (!activeCreate && !retryCoolingDown && createdToday < settings.maxScriptsPerDay) {
      const job = queueMotPhutVoLeJob('create', { topic: '', category: '', count: 1, settings, design: getMotPhutVoLeVisualDesign(), autoGenerated: true });
      logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_AUTO_GENERATION_QUEUED',
        'Đã tự xếp hàng tạo video MPVL để bổ sung lịch đăng.', job.id);
    }
  }

  const statusDue = motPhutVoLeFacebookTokenSaved() && listMotPhutVoLeSchedules().find((item) => item.status === 'scheduled'
    && item.facebookScheduleState === 'scheduled'
    && Date.parse(item.scheduledAt) <= Date.now()
    && (!item.facebookCheckedAt || Date.parse(item.facebookCheckedAt) <= Date.now() - 60_000));
  if (statusDue) {
    const checkedAt = new Date().toISOString();
    try {
      const remote = await getMotPhutVoLeFacebookVideoStatus(statusDue.facebookVideoId);
      const remoteStatus = String(remote.status?.video_status || remote.status?.publishing_phase?.status || '').toLowerCase();
      if (remote.published === true || ['published', 'complete'].includes(remoteStatus)) {
        updateMotPhutVoLeSchedule(statusDue.id, { status: 'published', facebookScheduleState: 'published',
          publishedAt: checkedAt, facebookCheckedAt: checkedAt, facebookError: null });
        logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_FACEBOOK_PUBLISHED',
          'Facebook xác nhận đã đăng video MPVL ' + String(statusDue.contentId || '').slice(0, 8) + '.');
      } else if (['error', 'failed'].includes(remoteStatus)) {
        updateMotPhutVoLeSchedule(statusDue.id, { status: 'failed', facebookScheduleState: 'failed',
          facebookCheckedAt: checkedAt, facebookError: `Meta báo video MPVL đã đăng thất bại (${remoteStatus}).` });
        logMotPhutVoLeActivity('ERROR', 'MOT_PHUT_VO_LE_FACEBOOK_PUBLISH_FAILED',
          'Facebook báo đăng MPVL ' + String(statusDue.contentId || '').slice(0, 8) + ' thất bại (' + remoteStatus + ').');
      } else updateMotPhutVoLeSchedule(statusDue.id, { facebookCheckedAt: checkedAt, facebookError: null });
    } catch (error) {
      updateMotPhutVoLeSchedule(statusDue.id, { facebookCheckedAt: checkedAt, facebookError: String(error.message || error).slice(0, 900) });
      logMotPhutVoLeActivity('WARN', 'MOT_PHUT_VO_LE_FACEBOOK_STATUS_CHECK_FAILED',
        'Không kiểm tra được trạng thái đăng MPVL ' + String(statusDue.contentId || '').slice(0, 8) + ': ' + error.message);
      onError(error);
    }
  }

  if (!settings.autoPublishEnabled || !settings.facebookPageVerified || !settings.facebookPageId || !motPhutVoLeFacebookTokenSaved()) return;
  const candidate = listMotPhutVoLeSchedules().find((item) => item.status === 'scheduled'
    && item.facebookScheduleState === 'local'
    && Date.parse(item.scheduledAt) >= Date.now() + 10 * 60_000);
  if (!candidate) return;

  const claimed = updateMotPhutVoLeSchedule(candidate.id, { status: 'publishing', facebookScheduleState: 'queued', facebookError: null });
  if (!claimed) return;
  try {
    logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_FACEBOOK_SCHEDULE_UPLOAD_STARTED',
      'Bắt đầu tải video MPVL ' + candidate.contentId.slice(0, 8) + ' lên Facebook để đặt lịch.');
    const result = await scheduleMotPhutVoLeOnFacebook(claimed, {
      pageId: settings.facebookPageId,
      onUploadSession: (patch) => {
        updateMotPhutVoLeSchedule(claimed.id, patch);
        if (patch.facebookUploadSessionId) logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_FACEBOOK_UPLOAD_SESSION',
          'Facebook đã mở phiên tải video MPVL ' + candidate.contentId.slice(0, 8) + '.');
      },
      onFinishing: (patch) => {
        updateMotPhutVoLeSchedule(claimed.id, patch);
        logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_FACEBOOK_UPLOAD_FINISHING',
          'Đã tải xong video MPVL ' + candidate.contentId.slice(0, 8) + '; đang xác nhận lịch trên Facebook.');
      }
    });
    updateMotPhutVoLeSchedule(claimed.id, { status: 'scheduled', facebookScheduleState: 'scheduled',
      facebookVideoId: result.facebookVideoId, facebookError: null, facebookUploadSessionId: null,
      facebookUploadOffset: null, facebookUploadEndOffset: null });
    logMotPhutVoLeActivity('INFO', 'MOT_PHUT_VO_LE_FACEBOOK_SCHEDULED',
      'Facebook đã nhận lịch đăng MPVL ' + candidate.contentId.slice(0, 8) + ' vào ' + candidate.scheduledAt + '.');
  } catch (error) {
    updateMotPhutVoLeSchedule(claimed.id, {
      status: error.facebookOutcomeUnknown ? 'failed' : 'scheduled',
      facebookScheduleState: error.facebookOutcomeUnknown ? 'uncertain' : 'failed',
      facebookError: String(error.message || error).slice(0, 900)
    });
    logMotPhutVoLeActivity('ERROR', 'MOT_PHUT_VO_LE_FACEBOOK_SCHEDULE_FAILED',
      'Không thể tải hoặc đặt lịch MPVL ' + candidate.contentId.slice(0, 8) + ' lên Facebook: ' + error.message);
    onError(error);
  }
}

export function motPhutVoLeSchedulerShouldStayAwake() {
  const settings = getMotPhutVoLeSettings();
  return settings.autoScheduleEnabled || settings.autoGenerationEnabled
    || (settings.autoPublishEnabled && settings.facebookPageVerified && settings.facebookPageId && motPhutVoLeFacebookTokenSaved()
      && listMotPhutVoLeSchedules().some((item) => item.status === 'scheduled' && item.facebookScheduleState === 'local'))
    || (settings.facebookPageVerified && settings.facebookPageId && motPhutVoLeFacebookTokenSaved()
      && listMotPhutVoLeSchedules().some((item) => item.status === 'scheduled' && item.facebookScheduleState === 'scheduled'));
}

export function motPhutVoLeScheduleStatus() {
  const settings = getMotPhutVoLeSettings();
  return {
    enabled: Boolean(settings.autoScheduleEnabled || settings.autoGenerationEnabled || settings.autoPublishEnabled),
    pageReady: Boolean(settings.facebookPageVerified && settings.facebookPageId && motPhutVoLeFacebookTokenSaved()),
    schedules: listMotPhutVoLeSchedules()
  };
}

