import { TIMEZONE } from '../config.mjs';
import { localScheduleSlot, startOfLocalDay, zonedLocalToDate } from '../scheduler/time.mjs';
import {
  claimThingsYouDidntKnowUploadSchedule, createThingsYouDidntKnowSchedule, getNextThingsYouDidntKnowStatusCheck,
  getNextThingsYouDidntKnowUploadSchedule, getThingsYouDidntKnowContent, getThingsYouDidntKnowDueSchedule,
  listThingsYouDidntKnowContents, listThingsYouDidntKnowJobs, listThingsYouDidntKnowSchedules,
  logThingsYouDidntKnowActivity, queueThingsYouDidntKnowJob, updateThingsYouDidntKnowSchedule
} from './history.mjs';
import { getThingsYouDidntKnowSettings } from './settings-store.mjs';
import { getThingsYouDidntKnowSourceVisualDesign } from './source-visual-design-store.mjs';
import { getThingsYouDidntKnowFacebookVideoStatus, scheduleThingsYouDidntKnowOnFacebook } from './facebook-publisher.mjs';

let tickRunning = false;

export function createThingsYouDidntKnowManualSchedule(contentId, scheduledAt, { adapter = null } = {}) {
  const settings = getThingsYouDidntKnowSettings();
  const selectedAdapter = adapter === 'meta' ? 'meta' : (adapter === 'mock' ? 'mock' : settings.facebookAdapter);
  let targetPageId = '';
  if (selectedAdapter === 'meta') {
    if (!settings.facebookPageId || !settings.facebookPageVerified) throw new Error('Hãy lưu và xác minh Facebook Page riêng trước khi lên lịch Live.');
    targetPageId = settings.facebookPageId;
  }
  return createThingsYouDidntKnowSchedule(contentId, scheduledAt, { adapter: selectedAdapter, targetPageId });
}

function minuteSlot(date) { return localScheduleSlot(date, TIMEZONE); }

function deterministicAutoSlots(existingSchedules, days, postsPerDay) {
  const occupied = new Map();
  for (const schedule of existingSchedules.filter((item) => item.status !== 'cancelled')) {
    const slot = minuteSlot(schedule.scheduledAt);
    occupied.set(slot.day, (occupied.get(slot.day) || 0) + 1);
  }
  const today = startOfLocalDay(new Date(), TIMEZONE);
  const hours = [9, 12, 15, 18];
  const slots = [];
  for (let offset = 0; offset < Math.max(1, Number(days) || 1); offset += 1) {
    const localDate = new Date(today.getTime() + offset * 24 * 60 * 60 * 1000);
    const day = minuteSlot(localDate).day;
    let used = occupied.get(day) || 0;
    for (const hour of hours) {
      if (used >= postsPerDay) break;
      const at = zonedLocalToDate(day + 'T' + String(hour).padStart(2, '0') + ':00', TIMEZONE);
      if (at.getTime() < Date.now() + 15 * 60_000) continue;
      if (existingSchedules.some((schedule) => schedule.status !== 'cancelled' && Math.abs(Date.parse(schedule.scheduledAt) - at.getTime()) < 60_000)) continue;
      slots.push(at);
      used += 1;
    }
  }
  return slots;
}

export async function processThingsYouDidntKnowScheduleTick({ onError = () => {} } = {}) {
  if (tickRunning) return;
  tickRunning = true;
  try {
    const settings = getThingsYouDidntKnowSettings();
    const activeJobs = listThingsYouDidntKnowJobs(500).some((job) => ['pending', 'running'].includes(job.status));
    const today = minuteSlot(new Date()).day;
    const jobs = listThingsYouDidntKnowJobs(500);
    const createdToday = jobs.filter((job) => minuteSlot(job.createdAt).day === today).length;
    if (settings.fullAutoEnabled && settings.autoGenerationEnabled && !activeJobs && createdToday < settings.maxScriptsPerDay) {
      const content = listThingsYouDidntKnowContents({ limit: 500 });
      const pendingReview = content.some((item) => item.sourceStatus !== 'human-reviewed' && ['needs_review', 'script_ready', 'audio_ready', 'failed'].includes(item.status));
      const readyCount = content.filter((item) => item.videoPath && item.sourceStatus === 'human-reviewed').length;
      const targetCount = settings.postsPerDay * settings.prepareAheadDays;
      if (!pendingReview && readyCount < targetCount) {
        const job = queueThingsYouDidntKnowJob({
          autoGenerated: true,
          settingsSnapshot: settings,
          designSnapshot: getThingsYouDidntKnowSourceVisualDesign()
        });
        logThingsYouDidntKnowActivity({ jobId: job.id, stage: 'full-auto', code: 'TYDK_FULL_AUTO_CREATED',
          message: 'Full Auto đã xếp một job tạo Reel; fact sẽ cần được duyệt trước khi lên lịch.' });
      }
    }

    if (settings.fullAutoEnabled && settings.autoPublishEnabled
      && (settings.facebookAdapter !== 'meta' || settings.facebookPageVerified)) {
      const content = listThingsYouDidntKnowContents({ limit: 500 })
        .filter((item) => item.videoPath && item.sourceStatus === 'human-reviewed')
        .sort((left, right) => Date.parse(left.createdAt) - Date.parse(right.createdAt));
      const schedules = listThingsYouDidntKnowSchedules();
      const alreadyAssigned = new Set(schedules.filter((item) => item.status !== 'cancelled').map((item) => item.contentId));
      const slots = deterministicAutoSlots(schedules, settings.prepareAheadDays, settings.postsPerDay);
      let added = 0;
      for (const item of content) {
        if (added >= slots.length) break;
        if (alreadyAssigned.has(item.id)) continue;
        const schedule = createThingsYouDidntKnowSchedule(item.id, slots[added].toISOString(), {
          adapter: settings.facebookAdapter, targetPageId: settings.facebookAdapter === 'meta' ? settings.facebookPageId : ''
        });
        alreadyAssigned.add(item.id);
        added += 1;
        logThingsYouDidntKnowActivity({ contentId: item.id, stage: 'full-auto', code: 'TYDK_FULL_AUTO_SCHEDULED',
          message: 'Full Auto đã xếp Reel đã được duyệt vào lịch ' + schedule.scheduledAt + '.' });
      }
    }

    const dueMock = getThingsYouDidntKnowDueSchedule();
    if (dueMock?.adapter === 'mock') {
      updateThingsYouDidntKnowSchedule(dueMock.id, { status: 'published', facebookState: 'mock-published', facebookCheckedAt: new Date().toISOString() });
      logThingsYouDidntKnowActivity({ contentId: dueMock.contentId, stage: 'mock-published', code: 'TYDK_MOCK_PUBLISHED',
        message: 'Lịch Mock đã đến giờ; không có bài thật nào được gửi lên Facebook.' });
    }

    const uploadCandidate = getNextThingsYouDidntKnowUploadSchedule();
    if (uploadCandidate) {
      const claimed = claimThingsYouDidntKnowUploadSchedule(uploadCandidate.id);
      if (claimed) {
        const schedule = { ...claimed, content: getThingsYouDidntKnowContent(claimed.contentId) };
        try {
          logThingsYouDidntKnowActivity({ contentId: schedule.contentId, stage: 'facebook-upload',
            code: 'TYDK_FACEBOOK_SCHEDULE_UPLOAD_STARTED', message: 'Đang gửi Reel đã duyệt lên Facebook để xác nhận lịch.' });
          const result = await scheduleThingsYouDidntKnowOnFacebook(schedule, {
            onUpload: (upload) => updateThingsYouDidntKnowSchedule(schedule.id, { facebookState: 'uploading', upload }),
            onFinishing: (upload) => updateThingsYouDidntKnowSchedule(schedule.id, { facebookState: 'finishing', upload })
          });
          updateThingsYouDidntKnowSchedule(schedule.id, { status: 'scheduled', facebookState: 'scheduled',
            facebookVideoId: result.facebookVideoId, facebookError: null, upload: { ...(schedule.upload || {}), videoId: result.facebookVideoId, state: 'scheduled' } });
          logThingsYouDidntKnowActivity({ contentId: schedule.contentId, stage: 'facebook-scheduled',
            code: 'TYDK_FACEBOOK_SCHEDULED', message: "Meta đã xác nhận lịch đăng Reel Things You Didn't Know." });
        } catch (error) {
          updateThingsYouDidntKnowSchedule(schedule.id, {
            status: error.facebookOutcomeUnknown ? 'uncertain' : 'failed',
            facebookState: error.facebookOutcomeUnknown ? 'uncertain' : 'failed',
            facebookError: String(error.message || error).slice(0, 800)
          });
          logThingsYouDidntKnowActivity({ contentId: schedule.contentId, stage: 'facebook-failed', severity: error.facebookOutcomeUnknown ? 'WARN' : 'ERROR',
            code: error.facebookOutcomeUnknown ? 'TYDK_FACEBOOK_OUTCOME_UNCERTAIN' : 'TYDK_FACEBOOK_SCHEDULE_FAILED',
            message: String(error.message || error).slice(0, 800) });
          onError(error);
        }
      }
    }

    const due = getNextThingsYouDidntKnowStatusCheck();
    if (due) {
      try {
        const remote = await getThingsYouDidntKnowFacebookVideoStatus(due.facebookVideoId);
        const videoStatus = String(remote.status?.video_status || remote.status?.publishing_phase?.status || '').toLowerCase();
        if (remote.published === true || ['published', 'complete'].includes(videoStatus)) {
          updateThingsYouDidntKnowSchedule(due.id, { status: 'published', facebookState: 'published',
            facebookCheckedAt: new Date().toISOString(), facebookError: null });
          logThingsYouDidntKnowActivity({ contentId: due.contentId, stage: 'facebook-published', code: 'TYDK_FACEBOOK_PUBLISHED',
            message: 'Facebook xác nhận Reel đã đăng.' });
        } else if (['error', 'failed'].includes(videoStatus)) {
          updateThingsYouDidntKnowSchedule(due.id, { status: 'failed', facebookState: 'failed',
            facebookCheckedAt: new Date().toISOString(), facebookError: 'Meta báo Reel đã đăng thất bại (' + videoStatus + ').' });
        } else {
          updateThingsYouDidntKnowSchedule(due.id, { facebookCheckedAt: new Date().toISOString() });
        }
      } catch (error) {
        updateThingsYouDidntKnowSchedule(due.id, { facebookCheckedAt: new Date().toISOString(), facebookError: String(error.message || error).slice(0, 800) });
        onError(error);
      }
    }

    if (settings.fullAutoEnabled && settings.autoPublishEnabled
      && settings.facebookAdapter === 'meta' && !settings.facebookPageVerified) {
      logThingsYouDidntKnowActivity({ stage: 'full-auto', severity: 'WARN', code: 'TYDK_FULL_AUTO_BLOCKED',
        message: "Không đăng tự động: Page Things You Didn't Know chưa được xác minh." });
    }
  } catch (error) {
    onError(error);
    logThingsYouDidntKnowActivity({ stage: 'schedule-tick', severity: 'ERROR', code: 'TYDK_SCHEDULER_FAILED',
      message: String(error.message || error).slice(0, 800) });
  } finally { tickRunning = false; }
}
